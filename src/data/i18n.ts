/** Prefix a path with the site base (GitHub Pages serves the site from /Portfolio/). */
export function url(path = '') {
  const base = import.meta.env.BASE_URL.replace(/\/$/, '');
  const clean = path.replace(/^\//, '');
  return `${base}/${clean}`;
}

export function homePath(lang: Lang) {
  return lang === 'en' ? url('') : url('pt/');
}

export function projectPath(lang: Lang, slug: string) {
  return lang === 'en' ? url(`work/${slug}/`) : url(`pt/work/${slug}/`);
}
